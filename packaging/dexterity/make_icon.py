"""Generate the Dexterity Sheets app icon (original artwork, drawn in code).

The "linked cells" mark: a rounded tile shading from deep indigo to teal, a 3 x 3 grid of
spreadsheet cells, and three of them lit and joined by an amber line with a node in each, which
rises like a tick. It reads as a spreadsheet, connected data and work done, at every size.
Everything is plain geometry defined below (no font, no third-party art), by Dexterity Design
Services Pvt. Ltd. This file is the single source: every size and format is generated from it.

Writes, under assets/app-icon/:
  dexterity-sheets.svg              canonical vector artwork (512 x 512 viewBox)
  dexterity-sheets-1024.png         1024 px render of the full tile
  dexterity-sheets-macos-512.png    macOS runtime Dock icon (Apple grid: 824/1024 body, margin)
  dexterity-sheets.ico              Windows exe/installer/file-type icon, 16-256 px (embedded by build.rs)
  dexterity-sheets.icns             macOS bundle icon
  hicolor/<n>x<n>/apps/ai.storyteller.gridcraft.png   Linux icon theme, 16-512 px; the 256 px one
                                    is also the runtime window/taskbar icon on Windows and Linux
  hicolor/scalable/apps/ai.storyteller.gridcraft.svg  Linux scalable icon (copy of the SVG)

The hicolor file names keep the app id `ai.storyteller.gridcraft` (an internal identifier the
.desktop file and Wayland app id use); only the artwork changes.

Needs Pillow. Run from anywhere:  python packaging/dexterity/make_icon.py
"""

from __future__ import annotations

import pathlib

from PIL import Image, ImageDraw

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "assets" / "app-icon"
APP_ID = "ai.storyteller.gridcraft"

# Palette.
TILE_A = (30, 42, 120, 255)  # deep indigo #1e2a78, top left
TILE_B = (14, 140, 140, 255)  # teal #0e8c8c, bottom right
WHITE = (255, 255, 255, 255)
AMBER = (255, 176, 32, 255)  # #ffb020
CELL_ALPHA = 56  # of 255: the unlit cells

# Geometry in the 512 x 512 design space.
VIEW = 512
RADIUS = 112
CELL, GAP, ORIGIN = 96, 24, 88  # three cells of 96 with gaps of 24, from 88 to 424
CELL_R = 20
# The lit cells (column, row) in the order the line joins them: a rising tick.
LIT = [(0, 1), (1, 2), (2, 0)]
LINE_W = 30
NODE_R, DOT_R = 25, 9

HICOLOR = [16, 24, 32, 48, 64, 128, 256, 512]
ICO = [16, 20, 24, 32, 40, 48, 64, 128, 256]
MASTER = 2048  # supersampled master render


def cell_box(col: int, row: int) -> tuple[int, int, int, int]:
    x = ORIGIN + col * (CELL + GAP)
    y = ORIGIN + row * (CELL + GAP)
    return x, y, x + CELL, y + CELL


def centre(col: int, row: int) -> tuple[int, int]:
    x0, y0, x1, y1 = cell_box(col, row)
    return (x0 + x1) // 2, (y0 + y1) // 2


def svg() -> str:
    """The canonical artwork as SVG, matching the raster render."""
    cells = []
    for row in range(3):
        for col in range(3):
            x0, y0, x1, y1 = cell_box(col, row)
            lit = (col, row) in LIT
            fill = 'fill="#ffffff"' if lit else f'fill="#ffffff" fill-opacity="{CELL_ALPHA / 255:.3f}"'
            cells.append(f'<rect x="{x0}" y="{y0}" width="{x1 - x0}" height="{y1 - y0}" rx="{CELL_R}" {fill}/>')
    pts = " ".join(f"{x},{y}" for x, y in (centre(*c) for c in LIT))
    nodes = []
    for c in LIT:
        x, y = centre(*c)
        nodes.append(f'<circle cx="{x}" cy="{y}" r="{NODE_R}" fill="#ffb020"/><circle cx="{x}" cy="{y}" r="{DOT_R}" fill="#ffffff"/>')
    cells_s = "\n    ".join(cells)
    nodes_s = "\n    ".join(nodes)
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {VIEW} {VIEW}" width="{VIEW}" height="{VIEW}">
  <!-- Dexterity Sheets app icon ("linked cells"). Original artwork by Dexterity Design Services
       Pvt. Ltd., generated by packaging/dexterity/make_icon.py. -->
  <defs>
    <linearGradient id="tile" gradientUnits="userSpaceOnUse" x1="0" y1="0" x2="{VIEW}" y2="{VIEW}">
      <stop offset="0" stop-color="#1e2a78"/>
      <stop offset="1" stop-color="#0e8c8c"/>
    </linearGradient>
  </defs>
  <rect width="{VIEW}" height="{VIEW}" rx="{RADIUS}" fill="url(#tile)"/>
    {cells_s}
  <polyline points="{pts}" fill="none" stroke="#ffb020" stroke-width="{LINE_W}" stroke-linecap="round" stroke-linejoin="round"/>
    {nodes_s}
</svg>
"""


def render_master(detail: bool) -> Image.Image:
    """The tile at MASTER px. Without `detail` (small sizes) the unlit cells and the node dots,
    which turn to mush below 32 px, are left out."""
    size = MASTER
    s = size / VIEW
    # Diagonal gradient, indigo top left to teal bottom right: (x + y) / 2 as a mask.
    down = Image.linear_gradient("L")
    ramp = Image.blend(down, down.transpose(Image.Transpose.TRANSPOSE), 0.5).resize((size, size), Image.Resampling.BICUBIC)
    img = Image.composite(Image.new("RGBA", (size, size), TILE_B), Image.new("RGBA", (size, size), TILE_A), ramp)
    # Cells as masks composited in white: unlit ones faint, lit ones solid.
    for lit_pass in (False, True):
        if not lit_pass and not detail:
            continue
        mask = Image.new("L", (size, size), 0)
        md = ImageDraw.Draw(mask)
        for row in range(3):
            for col in range(3):
                if ((col, row) in LIT) != lit_pass:
                    continue
                x0, y0, x1, y1 = cell_box(col, row)
                md.rounded_rectangle([x0 * s, y0 * s, x1 * s, y1 * s], radius=CELL_R * s, fill=255 if lit_pass else CELL_ALPHA)
        img = Image.composite(Image.new("RGBA", (size, size), WHITE), img, mask)
    dr = ImageDraw.Draw(img)
    pts = [(x * s, y * s) for x, y in (centre(*c) for c in LIT)]
    dr.line(pts, fill=AMBER, width=round(LINE_W * s), joint="curve")
    for x, y in pts:
        r = NODE_R * s
        dr.ellipse([x - r, y - r, x + r, y + r], fill=AMBER)
        if detail:
            r = DOT_R * s
            dr.ellipse([x - r, y - r, x + r, y + r], fill=WHITE)
    shape = Image.new("L", (size, size), 0)
    ImageDraw.Draw(shape).rounded_rectangle([0, 0, size - 1, size - 1], radius=RADIUS * s, fill=255)
    img.putalpha(shape)
    return img


def scaled(master: Image.Image, n: int) -> Image.Image:
    return master.resize((n, n), Image.Resampling.LANCZOS)


def mac(master: Image.Image, n: int) -> Image.Image:
    """Apple's grid: an 824/1024 body centred with a transparent margin."""
    body = round(n * 824 / 1024)
    canvas = Image.new("RGBA", (n, n), (0, 0, 0, 0))
    off = (n - body) // 2
    canvas.paste(scaled(master, body), (off, off))
    return canvas


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    full = render_master(detail=True)
    # Below 32 px the faint cells turn to mush: the small sizes show the lit cells and the line.
    small = render_master(detail=False)

    def pick(n: int) -> Image.Image:
        return scaled(small if n < 32 else full, n)

    written = []

    def save(img: Image.Image, path: pathlib.Path, **kw) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        img.save(path, **kw)
        written.append(path)

    text = svg()
    for p in (OUT / "dexterity-sheets.svg", OUT / "hicolor" / "scalable" / "apps" / f"{APP_ID}.svg"):
        with open(p, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        written.append(p)

    save(pick(1024), OUT / "dexterity-sheets-1024.png", optimize=True)
    save(mac(full, 512), OUT / "dexterity-sheets-macos-512.png", optimize=True)
    for n in HICOLOR:
        save(pick(n), OUT / "hicolor" / f"{n}x{n}" / "apps" / f"{APP_ID}.png", optimize=True)

    ico_imgs = [pick(n) for n in ICO]
    save(ico_imgs[-1], OUT / "dexterity-sheets.ico", format="ICO", sizes=[(n, n) for n in ICO], append_images=ico_imgs[:-1])

    save(mac(full, 1024), OUT / "dexterity-sheets.icns", format="ICNS")

    for p in written:
        print(p.relative_to(ROOT).as_posix())


if __name__ == "__main__":
    main()
