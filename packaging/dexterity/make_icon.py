"""Generate the Dexterity Sheets app icon (original artwork, drawn in code).

A deep-blue rounded tile with a faint white spreadsheet grid and a bold white "D". Everything is
plain geometry defined below (no font, no third-party art), by Dexterity Design Services Pvt. Ltd.

Writes, under assets/app-icon/:
  dexterity-sheets.svg              canonical vector artwork (512 x 512 viewBox)
  dexterity-sheets-1024.png         1024 px render of the full tile
  dexterity-sheets-macos-512.png    macOS runtime Dock icon (Apple grid: 824/1024 body, margin)
  dexterity-sheets.ico              Windows exe/installer icon, 16-256 px (embedded by build.rs)
  dexterity-sheets.icns             macOS bundle icon
  hicolor/<n>x<n>/apps/ai.storyteller.gridcraft.png   Linux icon theme, 16-512 px; the 256 px one
                                    is also the runtime window/taskbar icon on Windows and Linux
  hicolor/scalable/apps/ai.storyteller.gridcraft.svg  Linux scalable icon (copy of the SVG)

The hicolor file names keep the app id `ai.storyteller.gridcraft` (an internal identifier the
.desktop file and Wayland app id use); only the artwork changes.

Needs Pillow. Run from anywhere:  python packaging/dexterity/make_icon.py
"""

from __future__ import annotations

import pathlib

from PIL import Image, ImageChops, ImageDraw

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "assets" / "app-icon"
APP_ID = "ai.storyteller.gridcraft"

# Palette.
TILE = (13, 59, 140, 255)  # deep blue #0d3b8c
TILE_DARK = (8, 40, 102, 255)  # lower edge shade #082866
WHITE = (255, 255, 255, 255)
GRID_ALPHA = 92  # of 255

# Geometry in the 512 x 512 design space.
VIEW = 512
RADIUS = 112
GRID_LO, GRID_HI, GRID_STEP, GRID_W = 64, 448, 96, 8
# The "D": a stem plus the right half of an ellipse, minus a counter of the same shape.
D_OUTER = (150, 120, 392, 260, 130, 136)  # x0, y_top, y_bottom, cx, rx, ry
D_INNER = (222, 184, 328, 260, 60, 72)
HALO = 14  # tile-coloured gap between the grid and the D (the counter is tile-coloured too)
D_HALO = (D_OUTER[0] - HALO, D_OUTER[1] - HALO, D_OUTER[2] + HALO, D_OUTER[3], D_OUTER[4] + HALO, D_OUTER[5] + HALO)

HICOLOR = [16, 24, 32, 48, 64, 128, 256, 512]
ICO = [16, 20, 24, 32, 40, 48, 64, 128, 256]
MASTER = 2048  # supersampled master render


def svg() -> str:
    """The canonical artwork as SVG, matching the raster render."""

    def d_path(x0: int, top: int, bottom: int, cx: int, rx: int, ry: int) -> str:
        return f"M{x0} {top} H{cx} A{rx} {ry} 0 0 1 {cx} {bottom} H{x0} Z"

    lines = []
    for v in range(GRID_LO, GRID_HI + 1, GRID_STEP):
        lines.append(f'<line x1="{v}" y1="{GRID_LO}" x2="{v}" y2="{GRID_HI}"/>')
        lines.append(f'<line x1="{GRID_LO}" y1="{v}" x2="{GRID_HI}" y2="{v}"/>')
    d = d_path(*D_OUTER) + " " + d_path(*D_INNER)
    grid_lines = "\n      ".join(lines)
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {VIEW} {VIEW}" width="{VIEW}" height="{VIEW}">
  <!-- Dexterity Sheets app icon. Original artwork by Dexterity Design Services Pvt. Ltd.,
       generated by packaging/dexterity/make_icon.py. -->
  <defs>
    <linearGradient id="tile" gradientUnits="userSpaceOnUse" x1="0" y1="0" x2="0" y2="{VIEW}">
      <stop offset="0" stop-color="#0d3b8c"/>
      <stop offset="1" stop-color="#082866"/>
    </linearGradient>
    <clipPath id="clip"><rect width="{VIEW}" height="{VIEW}" rx="{RADIUS}"/></clipPath>
  </defs>
  <g clip-path="url(#clip)">
    <rect width="{VIEW}" height="{VIEW}" fill="url(#tile)"/>
    <g stroke="#ffffff" stroke-opacity="{GRID_ALPHA / 255:.3f}" stroke-width="{GRID_W}" stroke-linecap="square">
      {grid_lines}
    </g>
    <path d="{d_path(*D_HALO)}" fill="url(#tile)"/>
    <path d="{d}" fill="#ffffff" fill-rule="evenodd"/>
  </g>
</svg>
"""


def d_mask(size: int, spec: tuple[int, int, int, int, int, int]) -> Image.Image:
    """Mask of a stem-plus-half-ellipse shape (the outer D or its counter)."""
    s = size / VIEW
    x0, top, bottom, cx, rx, ry = spec
    cy = (top + bottom) / 2
    rect = Image.new("L", (size, size), 0)
    ImageDraw.Draw(rect).rectangle([x0 * s, top * s, cx * s, bottom * s], fill=255)
    ell = Image.new("L", (size, size), 0)
    ImageDraw.Draw(ell).ellipse([(cx - rx) * s, (cy - ry) * s, (cx + rx) * s, (cy + ry) * s], fill=255)
    # Keep only the right half of the ellipse.
    ImageDraw.Draw(ell).rectangle([0, 0, cx * s, size], fill=0)
    return ImageChops.lighter(rect, ell)


def render_master(grid: bool) -> Image.Image:
    size = MASTER
    s = size / VIEW
    # Tile with a vertical gradient.
    grad = Image.new("RGBA", (1, size))
    for y in range(size):
        t = y / (size - 1)
        grad.putpixel((0, y), tuple(round(a + (b - a) * t) for a, b in zip(TILE, TILE_DARK)))
    tile = grad.resize((size, size))
    shape = Image.new("L", (size, size), 0)
    ImageDraw.Draw(shape).rounded_rectangle([0, 0, size - 1, size - 1], radius=RADIUS * s, fill=255)

    img = tile.copy()
    if grid:
        lines = Image.new("L", (size, size), 0)
        dr = ImageDraw.Draw(lines)
        half = GRID_W * s / 2
        for v in range(GRID_LO, GRID_HI + 1, GRID_STEP):
            dr.rectangle([v * s - half, GRID_LO * s - half, v * s + half, GRID_HI * s + half], fill=GRID_ALPHA)
            dr.rectangle([GRID_LO * s - half, v * s - half, GRID_HI * s + half, v * s + half], fill=GRID_ALPHA)
        img = Image.composite(Image.new("RGBA", (size, size), WHITE), img, lines)

    d = ImageChops.subtract(d_mask(size, D_OUTER), d_mask(size, D_INNER))
    # Halo: a larger solid D filled with the tile, so grid lines stop short of the letter.
    img = Image.composite(tile, img, d_mask(size, D_HALO))
    img = Image.composite(Image.new("RGBA", (size, size), WHITE), img, d)
    img.putalpha(shape)
    return img


def scaled(master: Image.Image, n: int) -> Image.Image:
    return master.resize((n, n), Image.Resampling.LANCZOS)


def mac(master: Image.Image, n: int) -> Image.Image:
    """Apple's grid: an 824/1024 body centred with a transparent margin."""
    body = round(n * 824 / 1024)
    canvas = Image.new("RGBA", (n, n), (0, 0, 0, 0))
    off = (n - body) // 2
    canvas.paste(scaled(master, body), (off, off))
    return canvas


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    full = render_master(grid=True)
    # Below 32 px the grid turns to mush: the small sizes show the tile and the D only.
    small = render_master(grid=False)

    def pick(n: int) -> Image.Image:
        return scaled(small if n < 32 else full, n)

    written = []

    def save(img: Image.Image, path: pathlib.Path, **kw) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        img.save(path, **kw)
        written.append(path)

    text = svg()
    for p in (OUT / "dexterity-sheets.svg", OUT / "hicolor" / "scalable" / "apps" / f"{APP_ID}.svg"):
        with open(p, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        written.append(p)

    save(pick(1024), OUT / "dexterity-sheets-1024.png", optimize=True)
    save(mac(full, 512), OUT / "dexterity-sheets-macos-512.png", optimize=True)
    for n in HICOLOR:
        save(pick(n), OUT / "hicolor" / f"{n}x{n}" / "apps" / f"{APP_ID}.png", optimize=True)

    ico_imgs = [pick(n) for n in ICO]
    save(ico_imgs[-1], OUT / "dexterity-sheets.ico", format="ICO", sizes=[(n, n) for n in ICO], append_images=ico_imgs[:-1])

    save(mac(full, 1024), OUT / "dexterity-sheets.icns", format="ICNS")

    for p in written:
        print(p.relative_to(ROOT).as_posix())


if __name__ == "__main__":
    main()
